// Identity comes from the Supabase (Google) access token. Existing members link their
// Google account once via action=redeem with a one-time activation PIN generated by admin.
// Member codes are internal IDs only — they were often shared, so they can't claim an account.

const MEMBER_FIELDS = 'code,name,email,status,expires_at,auth_user_id,activation_pin_expires_at';

const redeemAttempts = new Map();
const checkRedeemLimit = (key) => {
  const now = Date.now();
  const recent = (redeemAttempts.get(key) || []).filter(t => now - t < 15 * 60 * 1000);
  if (recent.length >= 10) return false;
  recent.push(now);
  redeemAttempts.set(key, recent);
  return true;
};

const parseBody = (req) => new Promise((resolve) => {
  let body = '';
  req.on('data', chunk => body += chunk);
  req.on('end', () => {
    try { resolve(JSON.parse(body || '{}')); }
    catch { resolve({}); }
  });
});

const toPublicMember = (m, user) => ({
  code:      m.code,
  name:      m.name || user.name || user.email.split('@')[0],
  email:     m.email || user.email,
  status:    m.status,
  expiresAt: m.expires_at,
  tier:      m.tier || 'library',
  // 'trial' = akses sementara dari admin: di aplikasi tetap ditawari upgrade ke Paket Imtihan.
  memberType: m.member_type || null,
});

const touchLastLogin = (code) => {
  const { url, key } = sbConfig();
  fetch(`${url}/rest/v1/members?code=eq.${encodeURIComponent(code)}`, {
    method: 'PATCH',
    headers: sbHeaders(key, { Prefer: 'return=minimal' }),
    body: JSON.stringify({ last_login: new Date().toISOString() }),
  }).catch(e => console.warn('[login] last_login update failed:', e.message));
};

async function handleSession(user, res) {
  const member = await resolveMember(user);
  if (!member) return res.status(200).json({ ok: false, status: 'not_member', email: user.email });
  if (member.status !== 'active') return res.status(200).json({ ok: false, status: member.status });
  touchLastLogin(member.code);
  return res.status(200).json({ ok: true, member: toPublicMember(member, user) });
}

async function handleRedeem(req, user, res) {
  const ip = (req.headers['x-forwarded-for'] || '').split(',')[0].trim() || req.headers['x-real-ip'] || 'unknown';
  if (!checkRedeemLimit(`user:${user.id}`) || (ip !== 'unknown' && !checkRedeemLimit(`ip:${ip}`))) {
    return res.status(429).json({ ok: false, status: 'rate_limited' });
  }

  const pin = normalizePin((await parseBody(req)).pin);
  if (!pin) return res.status(400).json({ ok: false, status: 'invalid' });

  const current = await resolveMember(user);
  if (current?.status === 'active' && current.tier !== 'free') {
    return res.status(200).json({ ok: true, member: toPublicMember(current, user) });
  }
  // Pemilik akun gratis yang ternyata member lama: akun gratisnya dilepas lalu diganti member lama.
  const freeAccount = current?.status === 'active' && current.tier === 'free' ? current : null;

  const { url, key } = sbConfig();
  const rows = await fetch(
    `${url}/rest/v1/members?activation_pin=eq.${encodeURIComponent(pin)}&select=${MEMBER_FIELDS}&limit=1`,
    { headers: sbHeaders(key) }
  ).then(r => r.json());
  const row = Array.isArray(rows) ? rows[0] : null;

  if (!row) return res.status(200).json({ ok: false, status: 'not_found' });
  if (row.activation_pin_expires_at && new Date(row.activation_pin_expires_at) < new Date()) {
    return res.status(200).json({ ok: false, status: 'pin_expired' });
  }
  if (row.status !== 'active') return res.status(200).json({ ok: false, status: row.status });
  if (row.auth_user_id && row.auth_user_id !== user.id) {
    return res.status(200).json({ ok: false, status: 'already_linked' });
  }

  // Conditional on the PIN still being unused and the row unlinked, so two accounts racing can't both win.
  // The PIN is cleared in the same update, making it single-use.
  const link = (patch) => fetch(
    `${url}/rest/v1/members?code=eq.${encodeURIComponent(row.code)}&activation_pin=eq.${encodeURIComponent(pin)}&auth_user_id=is.null&select=${MEMBER_FIELDS}`,
    {
      method: 'PATCH',
      headers: sbHeaders(key, { Prefer: 'return=representation' }),
      body: JSON.stringify({
        auth_user_id: user.id,
        activation_pin: null,
        activation_pin_expires_at: null,
        last_login: new Date().toISOString(),
        ...patch,
      }),
    }
  );

  const patchFree = (body) => fetch(`${url}/rest/v1/members?code=eq.${encodeURIComponent(freeAccount.code)}`, {
    method: 'PATCH',
    headers: sbHeaders(key, { Prefer: 'return=minimal' }),
    body: JSON.stringify(body),
  });
  if (freeAccount) {
    const detached = await patchFree({ auth_user_id: null, email: null, status: 'disabled', notes: `Diganti member lama ${row.code}` });
    if (!detached.ok) return res.status(200).json({ ok: false, status: 'error' });
  }

  let r = await link(row.email ? {} : { email: user.email });
  if (!r.ok) r = await link({}); // email already used by another member row
  const linked = await r.json().catch(() => []);
  if (!Array.isArray(linked) || !linked[0]) {
    if (freeAccount) await patchFree({ auth_user_id: user.id, email: freeAccount.email, status: 'active', notes: 'Akun gratis' });
    return res.status(200).json({ ok: false, status: 'already_linked' });
  }

  return res.status(200).json({ ok: true, member: toPublicMember(linked[0], user) });
}

// Login Google tanpa bayar → akun gratis terbatas (tier 'free').
async function handleStartFree(req, user, res) {
  const current = await resolveMember(user);
  if (current) {
    if (current.status !== 'active') return res.status(200).json({ ok: false, status: current.status });
    return res.status(200).json({ ok: true, member: toPublicMember(current, user) });
  }
  // Maks 20 akun gratis baru per IP per hari (Vercel mengisi x-real-ip dengan IP asli pengunjung).
  const ip = String(req.headers['x-real-ip'] || (req.headers['x-forwarded-for'] || '').split(',')[0] || '').trim();
  if (ip && !(await consumeQuota(`IP-${ip}`.slice(0, 60), 'signup', 20))) {
    return res.status(429).json({ ok: false, status: 'rate_limited' });
  }

  const { url, key } = sbConfig();
  const now = new Date().toISOString();
  for (let attempt = 0; attempt < 5; attempt++) {
    const r = await fetch(`${url}/rest/v1/members?select=code,name,email,status,expires_at,tier`, {
      method: 'POST',
      headers: sbHeaders(key, { Prefer: 'return=representation' }),
      body: JSON.stringify({
        code:            newMemberCode(),
        name:            (user.name || user.email.split('@')[0]).slice(0, 120),
        email:           user.email,
        auth_user_id:    user.id,
        whatsapp:        '',
        duration:        36500,
        status:          'active',
        tier:            'free',
        free_started_at: now,
        expires_at:      '2099-12-31',
        last_login:      now,
        notes:           'Akun gratis',
      }),
    });
    if (r.ok) {
      const rows = await r.json();
      return res.status(200).json({ ok: true, member: toPublicMember(rows[0], user) });
    }
    if (r.status !== 409) {
      console.error('[login:start-free]', r.status, await r.text());
      return res.status(200).json({ ok: false, status: 'error' });
    }
    // 409: kode bentrok (coba kode lain) atau akun sudah dibuat oleh permintaan paralel.
    const existing = await resolveMember(user);
    if (existing) return res.status(200).json({ ok: true, member: toPublicMember(existing, user) });
  }
  return res.status(200).json({ ok: false, status: 'error' });
}

// Alamat aplikasi untuk redirect setelah bayar. APP_URL (opsional) menang; selain itu host permintaan.
const appOrigin = (req) => {
  const fixed = (process.env.APP_URL || '').trim().replace(/\/+$/, '');
  if (/^https:\/\//i.test(fixed)) return fixed;
  const host = String(req.headers['x-forwarded-host'] || req.headers.host || '').split(',')[0].trim();
  return /^[a-z0-9.-]+(:\d+)?$/i.test(host) ? `${host.startsWith('localhost') ? 'http' : 'https'}://${host}` : null;
};

const checkoutAttempts = new Map();
const checkCheckoutLimit = (key) => {
  const now = Date.now();
  const recent = (checkoutAttempts.get(key) || []).filter(t => now - t < 10 * 60 * 1000);
  if (recent.length >= 12) return false;
  recent.push(now);
  checkoutAttempts.set(key, recent);
  return true;
};

const publicCheckout = (c) => ({ id: c.id, plan: c.plan, amount: c.amount, link: c.link, status: c.status });

// Buat tagihan Mayar untuk paket yang dipilih (harga ditentukan server, bukan browser).
async function handleCheckout(req, user, res) {
  if (!mayarConfigured()) return res.status(200).json({ ok: false, status: 'payments_disabled' });
  const { plan, seats, partner: partnerSlug, ref } = await parseBody(req);
  if (!CHECKOUT_PLANS.includes(plan)) return res.status(400).json({ ok: false, status: 'invalid_plan' });
  if (!checkCheckoutLimit(user.id)) return res.status(429).json({ ok: false, status: 'rate_limited' });

  const member = await resolveMember(user);
  if (member && member.status !== 'active') return res.status(200).json({ ok: false, status: member.status });
  const blocked = checkoutBlockReason(plan, member);
  if (blocked) return res.status(200).json({ ok: false, status: blocked });

  const offer = plan === 'imtihan' ? await getWelcomeOffer(member) : null;
  // Tautan kerja sama: akun yang sudah ditandai ke satu kekeluargaan tetap tercatat ke sana, walau memakai tautan lain.
  // Yang menekan bayar setelah tautannya berakhir diberi tahu, bukan diam-diam ditagih harga normal.
  const tagged = plan === 'imtihan' && member ? (await readMemberReferral(member.code))?.partner_slug : null;
  const partner = plan !== 'imtihan' ? null
    : (tagged && await getLivePartnerLink(tagged)) || (partnerSlug ? await getLivePartnerLink(partnerSlug) : null);
  if (plan === 'imtihan' && partnerSlug && !partner) return res.status(200).json({ ok: false, status: 'partner_closed' });
  // Program Mitra: akun yang diajak mitra dapat potongan; harga termurah yang menang (penawaran pribadi, mitra, kekeluargaan).
  const program = plan === 'imtihan' && member ? await readAffiliateProgram() : null;
  const affiliate = program?.open ? await resolveMemberAffiliate(member, ref).catch(() => null) : null;
  const affiliateAmount = affiliate ? affiliatePrice(await imtihanPrice(), program.discount) : null;
  const best = Math.min(offer?.price || Infinity, affiliateAmount || Infinity);
  const usePartner = partner && partner.price <= best;
  const result = await createCheckout({
    user, member, plan, appOrigin: appOrigin(req), seats,
    imtihanAmount: usePartner ? partner.price : (Number.isFinite(best) ? best : undefined),
    partnerSlug: usePartner ? partner.slug : undefined,
    // Tagihan lewat tautan kekeluargaan tidak diberi komisi mitra (bagiannya sudah untuk kas kekeluargaan).
    affiliate: affiliate && !usePartner ? { slug: affiliate.slug, percent: commissionPercent(affiliate, program) } : undefined,
  });
  if (!result.ok) return res.status(200).json(result);
  return res.status(200).json({ ok: true, checkout: publicCheckout(result.checkout) });
}

// Dipanggil berkala selama pembeli menunggu. Kalau Mayar sudah lunas, akses langsung diaktifkan.
async function handleCheckoutStatus(req, user, res) {
  const { id } = await parseBody(req);
  const checkout = await getOwnedCheckout(id, user.id);
  if (!checkout) return res.status(404).json({ ok: false, status: 'not_found' });
  let status = checkout.status;
  try {
    status = await refreshCheckout(checkout);
  } catch (err) {
    console.warn('[login:checkout-status]', err.message);
  }
  return res.status(200).json({ ok: true, status, plan: checkout.plan });
}

