/* Menandai akun gratis ke kekeluargaan yang tautannya dipakai. Sekali saja: tautan pertama yang menang, supaya akun
   tidak berpindah kekeluargaan. Mengembalikan tanda akun ini (juga dipakai halaman Gabung saat tautannya tidak dibawa). */
async function handlePartnerTag(req, user, res) {
  const ip = (req.headers['x-forwarded-for'] || '').split(',')[0].trim() || 'unknown';
  if (!checkTrackLimit(ip)) return res.status(429).json({ ok: false });
  const { slug } = await parseBody(req);
  const member = await resolveMember(user);
  if (!member) return res.status(200).json({ ok: true, slug: null });
  const row = await readMemberReferral(member.code);
  if (row?.partner_slug) return res.status(200).json({ ok: true, slug: row.partner_slug });
  const link = row?.tier === 'free' ? await getOpenPartnerLink(slug) : null;
  if (!link) return res.status(200).json({ ok: true, slug: null });
  const { url, key } = sbConfig();
  const r = await fetch(`${url}/rest/v1/members?code=eq.${encodeURIComponent(member.code)}&partner_slug=is.null`, {
    method: 'PATCH',
    headers: sbHeaders(key, { Prefer: 'return=minimal' }),
    body: JSON.stringify({ partner_slug: link.slug, partner_tagged_at: new Date().toISOString() }),
  });
  return res.status(200).json({ ok: true, slug: r.ok ? link.slug : null });
}

